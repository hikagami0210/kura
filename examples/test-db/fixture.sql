CREATE INDEX IF NOT EXISTS orders_customer_created_idx ON public.orders(customer_id,created_at DESC) INCLUDE(total_amount);
CREATE INDEX IF NOT EXISTS orders_pending_idx ON public.orders(created_at) WHERE status_code='pending';
CREATE TABLE IF NOT EXISTS audit.order_events(id integer PRIMARY KEY,order_id integer NOT NULL,event_type text NOT NULL);
COMMENT ON TABLE audit.order_events IS '外部キー制約を持たない注文履歴';
CREATE TABLE IF NOT EXISTS public.order_lines(order_id integer NOT NULL REFERENCES public.orders(id),line_no integer NOT NULL,product_name text NOT NULL,PRIMARY KEY(order_id,line_no));
CREATE TABLE IF NOT EXISTS audit.line_events(id integer PRIMARY KEY,order_id integer NOT NULL,line_no integer NOT NULL,FOREIGN KEY(order_id,line_no) REFERENCES public.order_lines(order_id,line_no));
CREATE OR REPLACE VIEW public.active_orders AS SELECT o.id,c.display_name AS customer_name,o.total_amount FROM public.orders o JOIN public.customers c ON c.id=o.customer_id WHERE o.status_code='processing';
COMMENT ON VIEW public.active_orders IS '処理中の注文と顧客名';
CREATE MATERIALIZED VIEW IF NOT EXISTS reporting.order_totals AS SELECT customer_id,SUM(total_amount) AS total FROM public.orders GROUP BY customer_id;
CREATE UNIQUE INDEX IF NOT EXISTS order_totals_customer_idx ON reporting.order_totals(customer_id);
COMMENT ON MATERIALIZED VIEW reporting.order_totals IS '顧客別の注文金額集計';
