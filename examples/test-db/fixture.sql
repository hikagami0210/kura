CREATE TABLE IF NOT EXISTS public.customers(id integer PRIMARY KEY,display_name text NOT NULL,email text);
CREATE TABLE IF NOT EXISTS public.orders(id integer PRIMARY KEY,customer_id integer NOT NULL REFERENCES public.customers(id),status_code text NOT NULL REFERENCES master.order_statuses(code),total_amount numeric(12,2) NOT NULL CHECK(total_amount>=0),created_at timestamptz NOT NULL DEFAULT now());
